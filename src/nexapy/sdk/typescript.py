"""NexaPy TypeScript Client SDK Generator."""

import json
from pathlib import Path
from nexapy import __version__


def generate_typescript_sdk(
    output_dir: Path,
    base_url: str = "http://localhost:8000",
    ai_path: str = "/ai/chat",
) -> None:
    """Generate TypeScript NexaPyClient SDK (`client.ts`, `types.ts`, `index.ts`)."""
    output_dir.mkdir(parents=True, exist_ok=True)
    clean_base_url_json = json.dumps(base_url.rstrip("/"))
    clean_ai_path_json = json.dumps("/" + ai_path.lstrip("/"))

    # 1. types.ts
    types_ts = f'''/**
 * NexaPy TypeScript SDK Types (v{__version__})
 * Auto-generated by NexaPy Framework CLI
 */
export type AIProvider = "freemodel" | "gemini" | "unknown" | (string & {{}});

export type AIProviderOption = "auto" | "openai" | "gemini" | "anthropic" | "deepseek" | "freemodel";

export type AIReasoningOption = "low" | "medium" | "high";

export interface AIResponse {{
  text: string;
  provider: AIProvider;
  model: string;
  success: boolean;
  error: string | null;
}}

export interface AIChatOptions {{
  provider?: AIProviderOption;
  reasoning?: AIReasoningOption;
  temperature?: number;
  maxTokens?: number;
  timeout?: number;
}}

export interface NexaPyClientOptions {{
  baseURL?: string;
  apiKey?: string;
  timeout?: number;
  aiPath?: string;
}}
'''
    (output_dir / "types.ts").write_text(types_ts, encoding="utf-8")

    # 2. client.ts
    client_ts = f'''import {{ AIResponse, AIChatOptions, NexaPyClientOptions }} from "./types";

/**
 * NexaPy TypeScript Client SDK (v{__version__})
 * Auto-generated by NexaPy Framework CLI
 */
export class NexaPyClient {{
  private baseURL: string;
  private apiKey?: string;
  private timeout: number;
  private aiPath: string;

  constructor(options: NexaPyClientOptions = {{}}) {{
    this.baseURL = (options.baseURL || {clean_base_url_json}).replace(/\\/+$/, "");
    this.apiKey = options.apiKey;
    this.timeout = options.timeout !== undefined ? options.timeout : 30000;
    this.aiPath = options.aiPath || {clean_ai_path_json};
  }}

  private getHeaders(customHeaders: Record<string, string> = {{}}): Record<string, string> {{
    const headers: Record<string, string> = {{
      "Content-Type": "application/json",
      "Accept": "application/json",
      ...customHeaders,
    }};
    if (this.apiKey) {{
      headers["X-NexaPy-Key"] = this.apiKey;
    }}
    return headers;
  }}

  async chat(prompt: string, options: AIChatOptions = {{}}): Promise<AIResponse> {{
    if (!prompt || !prompt.trim()) {{
      throw new Error("NexaPyClient: prompt parameter is required and cannot be empty.");
    }}

    const payload: Record<string, unknown> = {{ prompt }};
    if (options.provider) payload.provider = options.provider;
    if (options.reasoning) payload.reasoning = options.reasoning;
    if (options.temperature !== undefined) payload.temperature = options.temperature;
    if (options.maxTokens !== undefined) payload.max_tokens = options.maxTokens;

    const reqTimeout = options.timeout !== undefined ? options.timeout : this.timeout;
    const controller = typeof AbortController !== "undefined" ? new AbortController() : null;
    const timer = controller && reqTimeout > 0 ? setTimeout(() => controller.abort(), reqTimeout) : null;

    try {{
      const response = await fetch(`${{this.baseURL}}${{this.aiPath}}`, {{
        method: "POST",
        headers: this.getHeaders(),
        body: JSON.stringify(payload),
        signal: controller ? controller.signal : undefined,
      }});

      let data: any;
      try {{
        data = await response.json();
      }} catch (_jsonErr) {{
        return {{
          text: "",
          provider: options.provider || "unknown",
          model: "unknown",
          success: false,
          error: `HTTP ${{response.status}} Invalid JSON Response`,
        }};
      }}

      if (!response.ok) {{
        return {{
          text: "",
          provider: options.provider || "unknown",
          model: "unknown",
          success: false,
          error: data.detail || data.error || `HTTP ${{response.status}} Error`,
        }};
      }}

      return {{
        text: data.text || "",
        provider: data.provider || "unknown",
        model: data.model || "unknown",
        success: data.success ?? true,
        error: data.error || null,
      }};
    }} catch (err: any) {{
      const errorMsg = err && err.name === "AbortError"
        ? `Request timed out after ${{reqTimeout}}ms`
        : (err && err.message ? err.message : "Network request failed");

      return {{
        text: "",
        provider: options.provider || "unknown",
        model: "unknown",
        success: false,
        error: errorMsg,
      }};
    }} finally {{
      if (timer) clearTimeout(timer);
    }}
  }}

  async executeWorkflow(workflowName: string, input: Record<string, unknown> = {{}}, step?: string): Promise<any> {{
    const query = step ? `?step=${{encodeURIComponent(step)}}` : "";
    const response = await fetch(`${{this.baseURL}}/workflows/${{encodeURIComponent(workflowName)}}${{query}}`, {{
      method: "POST",
      headers: this.getHeaders(),
      body: JSON.stringify(input),
    }});
    return await response.json();
  }}

  async getExecution(executionId: string): Promise<any> {{
    const response = await fetch(`${{this.baseURL}}/workflows/executions/${{encodeURIComponent(executionId)}}`, {{
      method: "GET",
      headers: this.getHeaders(),
    }});
    return await response.json();
  }}

  async listWorkflows(): Promise<any> {{
    const response = await fetch(`${{this.baseURL}}/workflows/_schema`, {{
      method: "GET",
      headers: this.getHeaders(),
    }});
    return await response.json();
  }}

  async health(): Promise<any> {{
    const response = await fetch(`${{this.baseURL}}/health`, {{
      method: "GET",
    }});
    return await response.json();
  }}

  async request(method: string, path: string, body?: any): Promise<any> {{
    const cleanPath = "/" + path.replace(/^\\/+/, "");
    const options: RequestInit = {{
      method: method.toUpperCase(),
      headers: this.getHeaders(),
    }};
    if (body && ["POST", "PUT", "PATCH"].includes(options.method!)) {{
      options.body = JSON.stringify(body);
    }}
    const response = await fetch(`${{this.baseURL}}${{cleanPath}}`, options);
    return await response.json();
  }}
}}
'''
    (output_dir / "client.ts").write_text(client_ts, encoding="utf-8")

    # 3. index.ts
    index_ts = f'''/**
 * NexaPy TypeScript SDK Entrypoint (v{__version__})
 * Auto-generated by NexaPy Framework CLI
 */
export * from "./types";
export * from "./client";
'''
    (output_dir / "index.ts").write_text(index_ts, encoding="utf-8")
